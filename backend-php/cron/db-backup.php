<?php

declare(strict_types=1);

/**
 * Dumps every table in the app database to a timestamped, gzip-compressed
 * SQL file in ../backups/ (a sibling of public_html/, never web-accessible
 * — see docs/DEPLOYMENT.md), then deletes old backups beyond RETENTION_COUNT.
 *
 * Written in pure PHP + PDO rather than shelling out to `mysqldump`,
 * because shared hosting frequently disables shell_exec()/exec()/proc_open()
 * entirely, and this must work without assuming any of them are available.
 *
 * Intended invocation: DirectAdmin cron job running
 *   php -q /home/<user>/domains/vault.soricu.com/cron/db-backup.php
 * See docs/DEPLOYMENT.md for the exact cron setup and the URL-triggered
 * fallback if your DirectAdmin only supports fetching a URL, not a command.
 *
 * Deliberately does NOT reuse lib/db.php's pk_db() — that helper's failure
 * path calls PHP's header()/http_response_code() and a bare `exit;` (exit
 * code 0), which is the right behavior for an HTTP response but would make
 * a database failure here look like a *successful* cron run to anything
 * watching the exit code. This script connects directly and exits non-zero
 * on failure instead.
 */

const RETENTION_COUNT = 14; // keep the most recent 14 backups (~2 weeks at one/day)

require __DIR__ . '/../lib/config.php';

$configPath = __DIR__ . '/../config/config.php';
if (!is_file($configPath)) {
    fwrite(STDERR, "db-backup: config/config.php not found - see docs/DEPLOYMENT.md setup.\n");
    exit(1);
}

$config = pk_config();
$db = $config['db'];

try {
    $dsn = sprintf(
        'mysql:host=%s;port=%s;dbname=%s;charset=%s',
        $db['host'],
        $db['port'] ?? '3306',
        $db['name'],
        $db['charset'] ?? 'utf8mb4'
    );
    $pdo = new PDO($dsn, $db['user'], $db['pass'], [
        PDO::ATTR_ERRMODE            => PDO::ERRMODE_EXCEPTION,
        PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
    ]);
} catch (PDOException $e) {
    fwrite(STDERR, 'db-backup: could not connect to the database: ' . $e->getMessage() . "\n");
    exit(1);
}

$backupDir = __DIR__ . '/../backups';
if (!is_dir($backupDir) && !mkdir($backupDir, 0700, true) && !is_dir($backupDir)) {
    fwrite(STDERR, "db-backup: could not create $backupDir\n");
    exit(1);
}

$useGzip = function_exists('gzopen');
$timestamp = date('Y-m-d-His');
$filename = 'passkeeper-' . $timestamp . ($useGzip ? '.sql.gz' : '.sql');
$path = $backupDir . '/' . $filename;

$handle = $useGzip ? gzopen($path, 'wb9') : fopen($path, 'wb');
if ($handle === false) {
    fwrite(STDERR, "db-backup: could not open $path for writing\n");
    exit(1);
}
$write = $useGzip ? 'gzwrite' : 'fwrite';

try {
    $write($handle, "-- Pass Keeper backup — {$timestamp}\n-- Generated by cron/db-backup.php\n\n");
    $write($handle, "SET FOREIGN_KEY_CHECKS=0;\n\n");

    $tables = $pdo->query('SHOW TABLES')->fetchAll(PDO::FETCH_COLUMN);

    foreach ($tables as $table) {
        $safeTable = preg_replace('/[^A-Za-z0-9_]/', '', $table); // table names aren't bindable params; this is not user input, just belt-and-suspenders
        if ($safeTable !== $table) {
            throw new RuntimeException("Unexpected table name from SHOW TABLES: {$table}");
        }

        $createRow = $pdo->query("SHOW CREATE TABLE `{$table}`")->fetch();
        $write($handle, "DROP TABLE IF EXISTS `{$table}`;\n");
        $write($handle, $createRow['Create Table'] . ";\n\n");

        $rowCount = 0;
        $stmt = $pdo->query("SELECT * FROM `{$table}`");
        while ($row = $stmt->fetch()) {
            $columns = array_map(static fn ($c) => "`{$c}`", array_keys($row));
            $values = array_map(
                static fn ($v) => $v === null ? 'NULL' : $pdo->quote((string) $v),
                array_values($row)
            );
            $write($handle, 'INSERT INTO `' . $table . '` (' . implode(', ', $columns) . ') VALUES (' . implode(', ', $values) . ");\n");
            $rowCount++;
        }
        $write($handle, "\n");
        fwrite(STDOUT, "db-backup: {$table} — {$rowCount} rows\n");
    }

    $write($handle, "SET FOREIGN_KEY_CHECKS=1;\n");
} catch (Throwable $e) {
    $useGzip ? gzclose($handle) : fclose($handle);
    unlink($path); // don't leave a half-written backup lying around
    fwrite(STDERR, 'db-backup: failed: ' . $e->getMessage() . "\n");
    exit(1);
}

$useGzip ? gzclose($handle) : fclose($handle);
chmod($path, 0600);

fwrite(STDOUT, sprintf("db-backup: wrote %s (%.1f KB)\n", $path, filesize($path) / 1024));

// --- Rotation: keep the most recent RETENTION_COUNT backups, delete the rest ---
$existing = glob($backupDir . '/passkeeper-*.sql*');
sort($existing); // the zero-padded timestamp in the filename sorts chronologically as a plain string
$toDelete = array_slice($existing, 0, max(0, count($existing) - RETENTION_COUNT));
foreach ($toDelete as $old) {
    if (unlink($old)) {
        fwrite(STDOUT, 'db-backup: rotated out ' . basename($old) . "\n");
    }
}

exit(0);
